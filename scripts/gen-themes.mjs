// Generate Material 3 color schemes (light + dark) from brand seed colors.
// Output:
//   portfolio/themes/<slug>.css   -> CSS custom properties --md-sys-color-*
//   assets/js/schemes.js          -> window.M3_SCHEMES for the landing page color demo
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { registerHooks } from 'node:module';

// material-color-utilities 0.4.0 ships a few extensionless relative imports
// (e.g. '../dynamiccolor/dynamic_color'), which strict Node ESM rejects.
// Retry those with '.js' appended.
registerHooks({
  resolve(specifier, context, next) {
    try {
      return next(specifier, context);
    } catch (err) {
      if (err.code === 'ERR_MODULE_NOT_FOUND' && specifier.startsWith('.') && !specifier.endsWith('.js')) {
        return next(`${specifier}.js`, context);
      }
      throw err;
    }
  },
});

const {
  argbFromHex, hexFromArgb, Hct, MaterialDynamicColors,
  SchemeContent, SchemeTonalSpot, SchemeVibrant, SchemeExpressive,
} = await import('@material/material-color-utilities');

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

// Seeds per portfolio. `variant` picks the M3 dynamic scheme flavour.
export const THEMES = [
  { slug: 'lumbung-niaga', label: 'Lumbung Niaga', seed: '#2E6B3A', variant: 'content' },
  { slug: 'rara-roastery', label: 'Rara Roastery', seed: '#9A4A22', variant: 'content' },
  { slug: 'kirana-ubud', label: 'Kirana Ubud', seed: '#1F6F66', variant: 'content' },
];
// Extra seeds shown only in the landing page "dynamic color" demo.
const DEMO_EXTRA = [
  { slug: 'ingatin', label: 'ingatin', seed: '#0073E6', variant: 'content' },
  { slug: 'plum', label: 'Plum', seed: '#7B3F8C', variant: 'content' },
  { slug: 'kunyit', label: 'Kunyit', seed: '#C28A00', variant: 'content' },
];

const VARIANTS = {
  content: SchemeContent,
  tonal: SchemeTonalSpot,
  vibrant: SchemeVibrant,
  expressive: SchemeExpressive,
};

const mdc = new MaterialDynamicColors();
const kebab = (s) => s.replace(/_/g, '-').replace(/([a-z])([A-Z])/g, '$1-$2').toLowerCase();

function scheme(seed, variant, isDark) {
  const Ctor = VARIANTS[variant];
  const s = new Ctor(Hct.fromInt(argbFromHex(seed)), isDark, 0, '2025');
  const out = {};
  for (const dc of mdc.allColors) {
    if (!dc || /palette-key-color|palette_key_color/.test(dc.name)) continue;
    out[kebab(dc.name)] = hexFromArgb(dc.getArgb(s));
  }
  return out;
}

const toVars = (obj) => Object.entries(obj).map(([k, v]) => `  --md-sys-color-${k}: ${v};`).join('\n');

mkdirSync(resolve(root, 'portfolio/themes'), { recursive: true });
for (const t of THEMES) {
  const light = scheme(t.seed, t.variant, false);
  const dark = scheme(t.seed, t.variant, true);
  const css = `/* Generated by scripts/gen-themes.mjs — seed ${t.seed} (${t.variant}, spec 2025). Do not edit by hand. */
:root, [data-theme="light"] {
  color-scheme: light;
${toVars(light)}
}
[data-theme="dark"] {
  color-scheme: dark;
${toVars(dark)}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${toVars(dark).replace(/^/gm, '  ')}
  }
}
`;
  writeFileSync(resolve(root, `portfolio/themes/${t.slug}.css`), css);
  console.log(`portfolio/themes/${t.slug}.css`, Object.keys(light).length, 'roles', 'primary', light.primary, '/', dark.primary);
}

const demo = {};
for (const t of [...DEMO_EXTRA.slice(0, 1), ...THEMES, ...DEMO_EXTRA.slice(1)]) {
  demo[t.slug] = { label: t.label, seed: t.seed, light: scheme(t.seed, t.variant, false), dark: scheme(t.seed, t.variant, true) };
}
mkdirSync(resolve(root, 'assets/js'), { recursive: true });
writeFileSync(resolve(root, 'assets/js/schemes.js'),
  `/* Generated by scripts/gen-themes.mjs. Do not edit by hand. */\nwindow.M3_SCHEMES = ${JSON.stringify(demo)};\n`);
console.log('assets/js/schemes.js', Object.keys(demo).join(', '));
