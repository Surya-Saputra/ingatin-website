// Generate Material 3 Expressive-style shapes as CSS clip-path polygons.
// Every shape has the same number of points, starting at the top and going
// clockwise, so any two shapes can be morphed with a CSS transition/animation.
// Output: portfolio/m3/shapes.css
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const N = 96;        // points per polygon (output)
const S = 1440;      // internal samples (for smoothing)
const TAU = Math.PI * 2;

// Radius functions r(t) where t in [0, TAU), t = 0 at the top, clockwise.
const lobes = (n, depth, p = 1) => (t) => (1 - depth) + depth * Math.pow(Math.abs(Math.cos((n * t) / 2)), p);
const waves = (n, depth, p = 1) => (t) => (1 - depth) + depth * Math.pow((Math.cos(n * t) + 1) / 2, p);
const polygon = (k, rot = 0) => (t) => {
  const seg = TAU / k;
  const a = ((t - rot) % seg + seg) % seg - seg / 2;
  return Math.cos(Math.PI / k) / Math.cos(a);
};

function smooth(arr, win, passes) {
  let a = arr;
  for (let p = 0; p < passes; p++) {
    const out = new Array(a.length);
    for (let i = 0; i < a.length; i++) {
      let s = 0;
      for (let j = -win; j <= win; j++) s += a[(i + j + a.length) % a.length];
      out[i] = s / (2 * win + 1);
    }
    a = out;
  }
  return a;
}

function build(fn, { smoothWin = 0, passes = 0 } = {}) {
  let r = Array.from({ length: S }, (_, i) => fn((i / S) * TAU));
  if (smoothWin) r = smooth(r, smoothWin, passes);
  const pts = [];
  for (let i = 0; i < N; i++) {
    const idx = Math.round((i / N) * S) % S;
    const t = (idx / S) * TAU;
    // t=0 at top, clockwise in screen coords (y down)
    pts.push([r[idx] * Math.sin(t), -r[idx] * Math.cos(t)]);
  }
  // Fit to the box (0..100%) on both axes.
  const xs = pts.map((p) => p[0]); const ys = pts.map((p) => p[1]);
  const [x0, x1, y0, y1] = [Math.min(...xs), Math.max(...xs), Math.min(...ys), Math.max(...ys)];
  return pts.map(([x, y]) => [((x - x0) / (x1 - x0)) * 100, ((y - y0) / (y1 - y0)) * 100]);
}

const SHAPES = {
  circle: build(() => 1),
  'cookie-4': build(lobes(4, 0.16, 0.55)),
  'cookie-6': build(lobes(6, 0.13, 0.55)),
  'cookie-9': build(lobes(9, 0.09, 0.6)),
  'cookie-12': build(lobes(12, 0.075, 0.6)),
  'clover-4': build(lobes(4, 0.34, 0.75)),
  'clover-8': build(lobes(8, 0.24, 0.7)),
  sunny: build(waves(8, 0.1)),
  'very-sunny': build(waves(8, 0.2)),
  'soft-burst': build(waves(10, 0.2, 1.6)),
  burst: build(waves(12, 0.24, 2.6)),
  flower: build(lobes(8, 0.3, 0.55)),
  pentagon: build(polygon(5, 0), { smoothWin: 34, passes: 3 }),
  gem: build(polygon(6, Math.PI / 6), { smoothWin: 30, passes: 3 }),
  square: build(polygon(4, Math.PI / 4), { smoothWin: 36, passes: 3 }),
  triangle: build(polygon(3, 0), { smoothWin: 46, passes: 3 }),
  oval: build((t) => 1 / Math.sqrt((Math.cos(t - Math.PI / 4) / 1) ** 2 + (Math.sin(t - Math.PI / 4) / 0.58) ** 2)),
};

const poly = (pts) => `polygon(${pts.map(([x, y]) => `${x.toFixed(2)}% ${y.toFixed(2)}%`).join(',')})`;

let css = `/* Generated by scripts/gen-shapes.mjs — ${N}-point clip-path polygons (morphable). Do not edit by hand. */\n:root {\n`;
for (const [name, pts] of Object.entries(SHAPES)) css += `  --m3-shape-${name}: ${poly(pts)};\n`;
css += '}\n';
for (const name of Object.keys(SHAPES)) css += `.shape-${name} { clip-path: var(--m3-shape-${name}); }\n`;

// Loading indicator (M3 Expressive): morphs through 7 shapes while rotating.
const seq = ['soft-burst', 'cookie-9', 'pentagon', 'oval', 'sunny', 'cookie-4', 'circle'];
css += '@keyframes m3-loader-morph {\n';
seq.forEach((name, i) => {
  css += `  ${((i / seq.length) * 100).toFixed(2)}% { clip-path: ${poly(SHAPES[name])}; }\n`;
});
css += `  100% { clip-path: ${poly(SHAPES[seq[0]])}; }\n}\n`;
css += `@keyframes m3-loader-spin { to { rotate: 1turn; } }
.m3-loader { display: inline-grid; place-items: center; width: 48px; height: 48px; flex: none; }
.m3-loader::before { content: ""; width: 38px; height: 38px; background: currentColor;
  animation: m3-loader-morph 4.9s cubic-bezier(.4,0,.2,1) infinite, m3-loader-spin 1.6s linear infinite; }
.m3-loader.contained { background: var(--md-sys-color-primary-container); color: var(--md-sys-color-on-primary-container); border-radius: 50%; }
.m3-loader.contained::before { width: 28px; height: 28px; }
@media (prefers-reduced-motion: reduce) { .m3-loader::before { animation-duration: 9s, 6s; } }
`;

mkdirSync(resolve(root, 'portfolio/m3'), { recursive: true });
writeFileSync(resolve(root, 'portfolio/m3/shapes.css'), css);
console.log('portfolio/m3/shapes.css', (css.length / 1024).toFixed(1), 'KB,', Object.keys(SHAPES).length, 'shapes');
